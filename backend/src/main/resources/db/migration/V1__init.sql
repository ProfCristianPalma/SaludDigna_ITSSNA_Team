-- V1: esquema inicial. payload y datos_pendientes son TEXT (no JSONB)
-- para que el mismo DDL sea compatible con PostgreSQL y con H2.
CREATE TABLE IF NOT EXISTS pacientes (
    id UUID PRIMARY KEY,
    nombre VARCHAR(255) NOT NULL,
    telefono VARCHAR(255) NOT NULL UNIQUE,
    email VARCHAR(255),
    fecha_nacimiento DATE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE IF NOT EXISTS estudios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255) NOT NULL,
    descripcion TEXT,
    precio NUMERIC(10, 2) NOT NULL,
    duracion_min INTEGER
);

CREATE TABLE IF NOT EXISTS clinicas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255) NOT NULL,
    ciudad VARCHAR(255) NOT NULL,
    direccion VARCHAR(255),
    telefono VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS tramites (
    id UUID PRIMARY KEY,
    folio VARCHAR(255) NOT NULL UNIQUE,
    paciente_id UUID NOT NULL REFERENCES pacientes (id),
    estudio_id BIGINT REFERENCES estudios (id),
    clinica_id BIGINT REFERENCES clinicas (id),
    estado VARCHAR(255) NOT NULL,
    canal_origen VARCHAR(255) NOT NULL,
    datos_pendientes TEXT,
    precio_cotizado NUMERIC(10, 2),
    fecha_cita TIMESTAMP,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE IF NOT EXISTS eventos (
    id UUID PRIMARY KEY,
    tramite_id UUID NOT NULL,
    tipo VARCHAR(255) NOT NULL,
    canal VARCHAR(255) NOT NULL,
    actor VARCHAR(255) NOT NULL,
    payload TEXT,
    timestamp TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_eventos_tramite_id ON eventos (tramite_id);

CREATE TABLE IF NOT EXISTS citas (
    id UUID PRIMARY KEY,
    tramite_id UUID NOT NULL UNIQUE REFERENCES tramites (id),
    fecha_hora TIMESTAMP NOT NULL,
    clinica_id BIGINT NOT NULL REFERENCES clinicas (id),
    estado VARCHAR(255) NOT NULL
);
